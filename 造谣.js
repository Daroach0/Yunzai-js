export class ZaoYao extends plugin {
  constructor() {
    super({
      name: "[example] 造谣",
      dsc: "随机给 @某人 生成一条造谣文案（纯属娱乐）",
      event: "message",
      priority: 10,
      rule: [
        {
          reg: "^#?造谣",
          fnc: "zaoYao",
        },
      ],
    })
  }

  async zaoYao() {
    const e = this.e
    let targetName = ""

    // 1. 优先判断有没有 @
    if (e.at) {
      targetName = String(e.at)
      try {
        if (e.isGroup && e.group?.pickMember) {
          const member = await e.group.pickMember(e.at).getInfo()
          targetName = member?.card || member?.nickname || targetName
        } else if (e.bot?.fl?.get?.(e.at)) {
          targetName = e.bot.fl.get(e.at)?.nickname || targetName
        }
      } catch (err) {
        logger.debug(`[造谣] 获取昵称失败：${err}`)
      }
    } else {
      // 2. 没有 @，就从消息里取“造谣”后面的内容
      const rawMsg = e.msg || e.raw_message || ""
      targetName = rawMsg.replace(/^#?造谣\s*/, "").trim()

      if (!targetName) {
        await e.reply("你想造谁的谣？请 @ 一个人，或者输入：造谣某某")
        return true
      }
    }

    // 3. 随机抽一条，把“某人”替换成目标名字
    const rumor = RUMORS[Math.floor(Math.random() * RUMORS.length)]
      .replace(/某人/g, targetName)

    // 4. 首尾加 # 发送
    await e.reply(`#${rumor}#`)
    return true
  }
}